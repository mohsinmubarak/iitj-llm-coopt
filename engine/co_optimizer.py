"""The co-optimizer: three controllers driven by one MetricsSnapshot per tick.

  DraftLengthController  one γ per step (0 included), learned online per decode-batch-size band
                         from measured tokens/s (contextual bandit), capped by system pressure.
                         (v1 used an analytic cost model with per-sequence γ; it lost to static
                         γ=4 on the 4090 rehearsal because of verification padding and because it
                         never chose γ=0 under saturation.)
  KVController           swap-vs-recompute per preemption (PCIe round trip vs prefill cost),
                         INT8/INT4 level from CPU-tier pressure.
  SchedulerController    AIMD batch cap, adaptive prefill chunk, pressure-aware admission
                         (defer long prompts under memory pressure), aged shortest-first
                         ordering, victim = most KV freed per unit of sunk work.

Coupling (the thesis claim) is the shared `pressure` level and cross-terms: high pressure
lowers the γ cap (each draft token reserves KV), defers long admissions and makes swapping
more attractive than recomputing on a busy GPU; low pressure restores swapped sequences first.

`coupled=False` (experiment C6) keeps the same three controllers but removes the shared view:
each reads only its own signals and refreshes on its own clock (γ every tick, KV every 2,
scheduler every 4), as three independently built systems would.
"""
import random
import time
from dataclasses import dataclass, field


from engine.policy import StaticPolicy



def expected_tokens(alpha: float, g: int) -> float:
    """E[tokens per verification] with γ drafts and i.i.d. acceptance α (Leviathan et al.)."""
    if g == 0:
        return 1.0
    if alpha >= 0.999:
        return g + 1.0
    return (1 - alpha ** (g + 1)) / (1 - alpha)


GAMMA_ARMS = (0, 1, 2, 3, 4, 6, 8)
BATCH_BUCKETS = (2, 4, 8, 16, 32, 64, 128)  # decode-batch size band edges


def batch_bucket(n: int) -> int:
    return sum(n >= e for e in BATCH_BUCKETS)


@dataclass
class DraftLengthController:
    """One γ per engine step, learned online (a contextual bandit over decode-batch-size bands).

    Reward = tokens generated by the step's decodes / step wall time (draft + verify), kept as an
    EMA per (band, γ). Every allowed γ is tried `min_trials` times per band, then ε-greedy.
    This measures what speculation really costs on this GPU, including the effects a step-time
    model missed in the first version (padding in verification graphs, prefill interleaving, the
    load at which drafting stops paying). One γ for the whole batch avoids padding every sequence
    to the largest γ. γ = 0 is an arm: under saturation no speculation is often best.

    Coupling: memory/queue pressure caps the allowed arms (each draft token reserves KV).
    """
    gamma_max: int = 8
    epsilon: float = 0.03
    min_trials: int = 4
    ema: float = 0.95
    seed: int = 0
    cap: int = 8
    base: int = 0
    stats: dict = field(default_factory=dict)   # (band, γ) -> (ema tokens/s, observations)

    def __post_init__(self):
        self.cap = self.gamma_max
        self.rng = random.Random(self.seed)

    def arms(self):
        return [g for g in GAMMA_ARMS if g <= min(self.cap, self.gamma_max)]

    def update(self, snap, pressure):
        cap = self.gamma_max
        if pressure is not None:  # coupled: memory/queue pressure caps speculation
            cap = {0: cap, 1: min(cap, 6), 2: min(cap, 3), 3: min(cap, 1)}[pressure]
        self.cap = cap

    def choose(self, n_decodes: int) -> int:
        b, arms = batch_bucket(n_decodes), self.arms()
        counts = {g: self.stats.get((b, g), (0.0, 0))[1] for g in arms}
        untried = [g for g in arms if counts[g] < self.min_trials]
        if untried:
            g = min(untried, key=lambda x: counts[x])
        elif self.rng.random() < self.epsilon:
            g = self.rng.choice(arms)
        else:
            g = max(arms, key=lambda x: self.stats[(b, x)][0])
        self.base = g
        return g

    def observe(self, g: int, n_decodes: int, tokens: int, step_s: float):
        if n_decodes == 0 or step_s <= 0:
            return
        key, r = (batch_bucket(n_decodes), g), tokens / step_s
        rate, cnt = self.stats.get(key, (r, 0))
        self.stats[key] = (self.ema * rate + (1 - self.ema) * r if cnt else r, cnt + 1)

    def best_for(self, n_decodes: int):
        """Learned best γ at this decode-batch size, or None if the band is still unexplored."""
        b = batch_bucket(n_decodes)
        seen = [g for g in GAMMA_ARMS if self.stats.get((b, g), (0.0, 0))[1] >= self.min_trials]
        return max(seen, key=lambda g: self.stats[(b, g)][0]) if seen else None

    def best_by_band(self) -> dict:
        """Current greedy choice per band (for traces and the thesis' γ-vs-load figure)."""
        out = {}
        for b in range(len(BATCH_BUCKETS) + 1):
            seen = [g for g in GAMMA_ARMS if (b, g) in self.stats]
            if seen:
                out[b] = max(seen, key=lambda g: self.stats[(b, g)][0])
        return out


@dataclass
class KVController:
    cpu_pressure_int4: float = 0.75   # switch new evictions to INT4 above this CPU-tier occupancy
    swap_fixed_s: float = 0.003       # per-swap launch/sync overhead (2 x layers of copy + quantize)
    # memory-elastic speculation (engine/elastic.py): park the drafter to grow the KV pool
    park_ticks: int = 2               # consecutive pressured ticks before parking
    unpark_ticks: int = 4             # consecutive calm ticks before restoring
    min_hold_s: float = 5.0           # minimum time between park/unpark decisions (no thrashing)
    unpark_max_usage: float = 0.6     # restore only if current sequences fill < 60 % of the base pool
    queue_hot: int = 8                # coupled: a waiting queue this long counts as pressure...
    queue_burst: int = 32             # ...and this long parks at once (a burst is under way)
    want_drafter: bool = True
    _hot: int = 0
    _calm: int = 0

    def update(self, snap, pressure, engine):
        if engine.kv_tiers:
            engine.kv_tiers.bits = 4 if snap.p_cpu > self.cpu_pressure_int4 else 8

    def update_drafter(self, snap, pressure, engine, gamma_ctl=None):
        """Coupled: shared pressure plus the γ controller's own verdict (speculation does not pay
        at this batch size). Independent (C6): only this controller's signals (KV use + queue)."""
        el = getattr(engine, "elastic", None)
        if el is None:
            return
        held = time.perf_counter() - el.last_change >= self.min_hold_s
        if not el.parked:
            burst = False
            if pressure is None:   # independent: memory signals only
                hot = snap.p_gpu >= 0.90 and snap.queue_depth > 0
            else:                  # coupled: memory pressure, the scheduler's queue, the γ verdict
                hot = pressure >= 2 or (snap.queue_depth >= self.queue_hot and snap.p_gpu >= 0.6)
                burst = snap.queue_depth >= self.queue_burst
                if gamma_ctl is not None and snap.queue_depth > 0 and gamma_ctl.best_for(snap.running) == 0:
                    hot = True
            # v2 (4090 rehearsal, W4): parking on memory pressure alone came too late in a burst;
            # the queue had already built up (burst SLO 0.24 vs 0.39 without a drafter).
            self._hot = self._hot + 1 if hot else 0
            if (burst or self._hot >= self.park_ticks) and held:
                self.want_drafter, self._hot = False, 0
        else:
            calm = snap.queue_depth == 0 and el.usage_if_unparked() <= self.unpark_max_usage
            if gamma_ctl is not None and gamma_ctl.best_for(snap.running) == 0:
                calm = False  # the γ controller has learned that drafting does not pay at this load
            self._calm = self._calm + 1 if calm else 0
            if self._calm >= self.unpark_ticks and held:
                self.want_drafter, self._calm = True, 0

    def swap_on_preempt(self, seq, engine, snap, pressure) -> bool:
        tiers, prof = engine.kv_tiers, engine.metrics.profile
        if not tiers or snap is None:
            return False
        nbytes = tiers.estimate_bytes(seq.num_computed, tiers.bits)
        swap_s = self.swap_fixed_s + nbytes / (prof.pcie_d2h_gbs * 1e9) + nbytes / (prof.pcie_h2d_gbs * 1e9)
        # a recompute rides along in a later batched prefill: its marginal cost is per-token only
        recompute_s = snap.target_b * seq.num_computed
        if pressure is not None and snap.running:
            # coupled: on a busy GPU recompute also delays every co-scheduled request
            recompute_s *= 1 + snap.queue_depth / snap.running
        return swap_s < recompute_s


@dataclass
class SchedulerController:
    ttft_slo: float = 2.0
    tpot_slo: float = 0.10
    min_seqs: int = 8
    max_seqs: int = 256
    chunk_small: int = 2048
    chunk_default: int = 8192
    chunk_large: int = 16384
    long_ctx: int = 4096
    aging_s: float = 5.0             # a request waiting this long is admitted regardless of size

    def update(self, snap, pressure, policy):
        if snap.preemption_rate > 0.05 or pressure == 3:
            policy.max_num_seqs = max(self.min_seqs, int(policy.max_num_seqs * 0.75))
        elif snap.queue_depth > 0 and (pressure is None or pressure <= 1):
            policy.max_num_seqs = min(self.max_seqs, policy.max_num_seqs + 8)
        if snap.ttft_p99_recent > self.ttft_slo and snap.queue_depth > 0:
            policy.max_batched_tokens = self.chunk_large
        elif snap.tpot_recent > self.tpot_slo:
            policy.max_batched_tokens = self.chunk_small
        else:
            policy.max_batched_tokens = self.chunk_default

    def admit(self, seq, engine, pressure) -> bool:
        if pressure is None or pressure < 2 or not engine.scheduler.running:
            return True
        waited = engine.now() - seq.arrival
        return len(seq.tokens) <= self.long_ctx or waited > self.aging_s

    def pick_next(self, waiting, engine, pressure) -> int:
        now, tiers = engine.now(), engine.kv_tiers
        best, best_score = 0, -1.0
        for i, s in enumerate(list(waiting)[:32]):
            score = (now - s.arrival + 0.1) / (1 + s.remaining / 2048)
            if pressure is not None and pressure <= 1 and tiers and tiers.has(s.seq_id):
                score *= 4  # restoring a swapped sequence is cheaper than a fresh prefill
            if score > best_score:
                best, best_score = i, score
        return best

    def preempt_victim(self, running):
        def freed_per_sunk_work(s):
            progress = s.num_generated / max(1, s.max_tokens)
            return len(s.tokens) * (1.0 - progress)
        return max(running, key=freed_per_sunk_work)


@dataclass
class CoOptimizer(StaticPolicy):
    enable_gamma: bool = True
    enable_kv: bool = True
    enable_sched: bool = True
    coupled: bool = True
    gamma_max: int = 8
    name = "coopt"

    def __post_init__(self):
        self.dl = DraftLengthController(gamma_max=self.gamma_max)
        self.kv = KVController()
        # The engine sizes its activation headroom for the configured max_batched_tokens, so the
        # controller may shrink prefill chunks under decode pressure but never grow them past it.
        self.sc = SchedulerController(chunk_default=self.max_batched_tokens, chunk_large=self.max_batched_tokens,
                                      chunk_small=max(256, self.max_batched_tokens // 4))
        self.kv_swap = self.enable_kv
        self.engine = None
        self.snap = None
        self.pressure = 0
        self.ticks = 0
        self.stale = {}  # independent mode: each controller's own last snapshot

    @staticmethod
    def pressure_level(snap) -> int:
        if snap.p_gpu >= 0.97 or snap.preemption_rate > 0.1:
            return 3
        if snap.p_gpu >= 0.90 or (snap.queue_depth > 0 and snap.p_gpu >= 0.85):
            return 2
        if snap.p_gpu >= 0.75:
            return 1
        return 0

    def tick(self, snap):
        self.ticks += 1
        self.snap = snap
        if self.coupled:
            self.pressure = self.pressure_level(snap)
            p = self.pressure
            if self.enable_gamma:
                self.dl.update(snap, p)
            if self.enable_kv:
                self.kv.update(snap, p, self.engine)
                self.kv.update_drafter(snap, p, self.engine, self.dl if self.enable_gamma else None)
            if self.enable_sched:
                self.sc.update(snap, p, self)
            return
        # independent controllers: no shared pressure, staggered refresh, own snapshot copies
        self.pressure = None
        if self.enable_gamma:
            self.stale["gamma"] = snap
            self.dl.update(snap, None)
        if self.enable_kv and self.ticks % 2 == 0:
            self.stale["kv"] = snap
            self.kv.update(snap, None, self.engine)
            self.kv.update_drafter(snap, None, self.engine)  # own signals only, no γ verdict
        if self.enable_sched and self.ticks % 4 == 0:
            self.stale["sched"] = snap
            self.sc.update(snap, None, self)

    # ---- hooks called by the engine ------------------------------------------------------
    def gamma_for_step(self, n_decodes, engine) -> int:
        return self.dl.choose(n_decodes) if self.enable_gamma else self.gamma

    def observe_step(self, gamma, n_decodes, tokens, step_s):
        if self.enable_gamma:
            self.dl.observe(gamma, n_decodes, tokens, step_s)

    def want_drafter(self, engine) -> bool:
        return self.kv.want_drafter if self.enable_kv else True

    def swap_on_preempt(self, seq, engine) -> bool:
        if not self.enable_kv:
            return False
        snap = self.snap if self.coupled else self.stale.get("kv", self.snap)
        return self.kv.swap_on_preempt(seq, engine, snap, self.pressure)

    def admit(self, seq, engine) -> bool:
        return self.sc.admit(seq, engine, self.pressure) if self.enable_sched else True

    def pick_next(self, waiting, engine) -> int:
        return self.sc.pick_next(waiting, engine, self.pressure) if self.enable_sched else 0

    def preempt_victim(self, running):
        return self.sc.preempt_victim(running) if self.enable_sched else running[-1]

    def state(self) -> dict:
        s = super().state()
        s.update({"gamma_base": self.dl.base if self.enable_gamma else self.gamma,
                  "gamma_cap": self.dl.cap if self.enable_gamma else self.gamma,
                  "pressure": -1 if self.pressure is None else self.pressure,
                  "kv_bits": self.engine.kv_tiers.bits if self.engine and self.engine.kv_tiers else 16})
        if self.enable_gamma:  # learned best γ per decode-batch band (band b covers n >= BATCH_BUCKETS[b-1])
            s.update({f"gamma_best_band{b}": g for b, g in self.dl.best_by_band().items()})
        return s
